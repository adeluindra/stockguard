-- Users: akun Admin dan Staff.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,

    role TEXT NOT NULL DEFAULT 'staff'
        CHECK (role IN ('admin', 'staff')),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT users_username_format_check
        CHECK (
            LENGTH(BTRIM(username)) BETWEEN 3 AND 50
            AND username = BTRIM(username)
        ),

    CONSTRAINT users_password_hash_nonblank_check
        CHECK (LENGTH(BTRIM(password_hash)) > 0)
);

-- Username unik tanpa membedakan huruf besar/kecil.
CREATE UNIQUE INDEX users_username_ci_uq
    ON users (LOWER(username));


-- Sessions: sesi login disimpan di PostgreSQL.
CREATE TABLE sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    token_hash BYTEA NOT NULL UNIQUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_activity_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,

    CONSTRAINT sessions_token_hash_length_check
        CHECK (OCTET_LENGTH(token_hash) = 32),

    CONSTRAINT sessions_expiry_check
        CHECK (expires_at > created_at),

    CONSTRAINT sessions_activity_check
        CHECK (
            last_activity_at >= created_at
            AND last_activity_at <= expires_at
        ),

    CONSTRAINT sessions_revocation_check
        CHECK (
            revoked_at IS NULL
            OR revoked_at >= created_at
        )
);

CREATE INDEX sessions_user_id_idx
    ON sessions (user_id);