
-- StockGuard Migration 000002
-- Products & Inventory Balances

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sku TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    low_stock_threshold BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT products_sku_format_check
        CHECK (
            CHAR_LENGTH(sku) BETWEEN 3 AND 64
            AND sku = BTRIM(sku)
        ),

    CONSTRAINT products_name_check
        CHECK (
            CHAR_LENGTH(name) BETWEEN 1 AND 200
            AND name = BTRIM(name)
        ),

    CONSTRAINT products_description_length_check
        CHECK (
            description IS NULL
            OR CHAR_LENGTH(description) <= 2000
        ),

    CONSTRAINT products_low_stock_check
        CHECK (low_stock_threshold >= 0)
);

-- SKU case-insensitive uniqueness.
CREATE UNIQUE INDEX products_sku_ci_uq
    ON products (LOWER(sku));


-- One inventory balance per product.
CREATE TABLE inventory_balances (
    product_id BIGINT PRIMARY KEY
        REFERENCES products(id) ON DELETE RESTRICT,

    on_hand BIGINT NOT NULL DEFAULT 0,
    reserved BIGINT NOT NULL DEFAULT 0,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT inventory_on_hand_check
        CHECK (on_hand >= 0),

    CONSTRAINT inventory_reserved_check
        CHECK (reserved >= 0),

    CONSTRAINT inventory_available_check
        CHECK (reserved <= on_hand)
);
