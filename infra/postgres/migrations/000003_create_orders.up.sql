
-- StockGuard Migration 000003
-- Orders & Order Items

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    created_by BIGINT NOT NULL,

    status TEXT NOT NULL DEFAULT 'reserved',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    fulfilled_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,

    CONSTRAINT orders_created_by_fk
        FOREIGN KEY (created_by)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT orders_status_check
        CHECK (
            status IN ('reserved', 'fulfilled', 'cancelled')
        ),

    CONSTRAINT orders_status_timestamps_check
        CHECK (
            (
                status = 'reserved'
                AND fulfilled_at IS NULL
                AND cancelled_at IS NULL
            )
            OR
            (
                status = 'fulfilled'
                AND fulfilled_at IS NOT NULL
                AND cancelled_at IS NULL
            )
            OR
            (
                status = 'cancelled'
                AND cancelled_at IS NOT NULL
                AND fulfilled_at IS NULL
            )
        ),

    CONSTRAINT orders_terminal_time_check
        CHECK (
            (
                fulfilled_at IS NULL
                OR fulfilled_at >= created_at
            )
            AND
            (
                cancelled_at IS NULL
                OR cancelled_at >= created_at
            )
        ),

    -- Supports the future composite FK from
    -- idempotency_records(order_id, user_id).
    CONSTRAINT orders_id_creator_uq
        UNIQUE (id, created_by)
);

-- List orders newest first.
CREATE INDEX orders_created_at_idx
    ON orders (created_at DESC, id DESC);

-- Filter orders by status.
CREATE INDEX orders_status_created_at_idx
    ON orders (status, created_at DESC, id DESC);


-- Products contained in each order.
CREATE TABLE order_items (
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,

    CONSTRAINT order_items_pk
        PRIMARY KEY (order_id, product_id),

    CONSTRAINT order_items_order_fk
        FOREIGN KEY (order_id)
        REFERENCES orders(id)
        ON DELETE RESTRICT,

    CONSTRAINT order_items_product_fk
        FOREIGN KEY (product_id)
        REFERENCES products(id)
        ON DELETE RESTRICT,

    CONSTRAINT order_items_quantity_check
        CHECK (quantity > 0)
);

-- Supports product-based lookups and FK operations.
CREATE INDEX order_items_product_id_idx
    ON order_items (product_id);
