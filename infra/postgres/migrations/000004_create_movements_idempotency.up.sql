
-- StockGuard Migration 000004
-- Inventory Movements & Order Idempotency

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL
        REFERENCES products(id) ON DELETE RESTRICT,

    order_id BIGINT,

    actor_user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    movement_type TEXT NOT NULL,
    delta_on_hand BIGINT NOT NULL,
    delta_reserved BIGINT NOT NULL,

    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- An order movement must refer to a product
    -- that actually belongs to the order.
    CONSTRAINT movements_order_item_fk
        FOREIGN KEY (order_id, product_id)
        REFERENCES order_items(order_id, product_id)
        ON DELETE RESTRICT,

    CONSTRAINT movements_type_delta_check
        CHECK (
            (
                movement_type = 'initial'
                AND order_id IS NULL
                AND delta_on_hand > 0
                AND delta_reserved = 0
            )
            OR
            (
                movement_type = 'adjustment'
                AND order_id IS NULL
                AND delta_on_hand <> 0
                AND delta_reserved = 0
            )
            OR
            (
                movement_type = 'reserve'
                AND order_id IS NOT NULL
                AND delta_on_hand = 0
                AND delta_reserved > 0
            )
            OR
            (
                movement_type = 'release'
                AND order_id IS NOT NULL
                AND delta_on_hand = 0
                AND delta_reserved < 0
            )
            OR
            (
                movement_type = 'fulfill'
                AND order_id IS NOT NULL
                AND delta_on_hand < 0
                AND delta_reserved = delta_on_hand
            )
        ),

    CONSTRAINT movements_reason_check
        CHECK (
            (reason IS NULL OR CHAR_LENGTH(reason) <= 500)
            AND (
                movement_type <> 'adjustment'
                OR (
                    reason IS NOT NULL
                    AND CHAR_LENGTH(BTRIM(reason))
                        BETWEEN 10 AND 500
                )
            )
        )
);

-- One movement of each order-related type per item.
CREATE UNIQUE INDEX movements_order_type_uq
    ON inventory_movements (
        order_id, product_id, movement_type
    )
    WHERE order_id IS NOT NULL;

-- Initial stock movement occurs at most once.
CREATE UNIQUE INDEX movements_initial_product_uq
    ON inventory_movements (product_id)
    WHERE movement_type = 'initial';

-- Product movement history.
CREATE INDEX movements_product_history_idx
    ON inventory_movements (
        product_id, created_at DESC, id DESC
    );

-- Global movement history.
CREATE INDEX movements_history_idx
    ON inventory_movements (
        created_at DESC, id DESC
);


-- Successful order idempotency records.
CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    idempotency_key TEXT NOT NULL,

    -- SHA-256 of canonicalized request payload.
    payload_hash BYTEA NOT NULL,

    -- A committed record always references an order.
    order_id BIGINT NOT NULL UNIQUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- User owning the key must be the order creator.
    CONSTRAINT idempotency_order_owner_fk
        FOREIGN KEY (order_id, user_id)
        REFERENCES orders(id, created_by)
        ON DELETE RESTRICT,

    CONSTRAINT idempotency_key_format_check
        CHECK (
            CHAR_LENGTH(idempotency_key) = 36
            AND idempotency_key = BTRIM(idempotency_key)
        ),

    CONSTRAINT idempotency_hash_length_check
        CHECK (OCTET_LENGTH(payload_hash) = 32)
);

CREATE UNIQUE INDEX idempotency_user_key_uq
    ON idempotency_records (
        user_id, idempotency_key
    );
